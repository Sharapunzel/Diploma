"""Persistence boundary for detector candidates and atomic transitions."""

from typing import Protocol


class DetectorRepository(Protocol):
    def read_context(self, detector_id) -> dict: ...
    def lock_context(self, detector_id) -> dict: ...
    def aggregate_context(self, aggregate_id, lock=False) -> dict: ...
    def create(self, values: dict) -> None: ...
    def next_working_point(self, schedule_id, after_index, evaluation_start_index): ...
    def working_inputs(self, schedule_id, starts: list) -> list: ...
    def attempt(self, attempt_id) -> dict: ...
    def select_attempt(self, context, attempt) -> None: ...
    def save_warmup_inputs(self, context, attempt_id, inputs, status, reason) -> None: ...
    def save_warmup(self, context, attempt_id, checkpoint, evaluation_start_index) -> None: ...
    def save_transition(self, context, point, checkpoint, outcome, finding) -> None: ...
    def diagnose(self, context, state, reason) -> None: ...
    def stop_for_aggregate(self, aggregate_id, reason, at) -> None: ...
