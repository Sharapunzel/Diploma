"""Persistence boundary for detector candidates and atomic transitions."""

from typing import Protocol


class DetectorRepository(Protocol):
    def command(self, actor, action, key): ...
    def receipt(self, actor, action, key, fingerprint, detector_id): ...
    def public_page(self, limit, offset, aggregate_id=None, execution_state=None): ...
    def public_context(self, detector_id): ...
    def public_warmup(self, attempt_id): ...
    def public_recovery(self, detector_id): ...
    def public_result(self, detector_id, index): ...
    def public_next_point(self, schedule_id, index): ...
    def check_owner(self, owner) -> None: ...
    def acquire_owner(self, owner_id, backend_pid): ...
    def candidates(self, after=None, limit=100): ...
    def recovery(self, detector_id): ...
    def last_result(self, detector_id, index): ...
    def record_recovery(self, context, reason, generation) -> None: ...
    def control(self, context, state, reason=None, new_request=False) -> None: ...
    def read_context(self, detector_id) -> dict: ...
    def history_metadata(self, detector_id, attempt_id) -> tuple[dict, dict]: ...
    def lock_context(self, detector_id) -> dict: ...
    def aggregate_context(self, aggregate_id, lock=False) -> dict: ...
    def create(self, values: dict) -> None: ...
    def next_working_point(self, schedule_id, after_index, evaluation_start_index): ...
    def working_inputs(self, schedule_id, starts: list, before_read=None) -> list: ...
    def attempt(self, attempt_id) -> dict: ...
    def select_attempt(self, context, attempt) -> None: ...
    def save_warmup_inputs(self, context, attempt_id, inputs, status, reason) -> None: ...
    def save_warmup(self, context, attempt_id, checkpoint, evaluation_start_index) -> None: ...
    def save_transition(self, context, point, checkpoint, outcome, finding) -> None: ...
    def diagnose(self, context, state, reason) -> None: ...
    def stop_for_aggregate(self, aggregate_id, reason, at) -> None: ...
