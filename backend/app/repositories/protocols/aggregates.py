"""Aggregate persistence boundary; application decisions remain in services."""

from __future__ import annotations

from datetime import datetime
from typing import Protocol
from uuid import UUID

from ...aggregation.results import AggregateStatistics
from ...aggregation.rules import CompiledRule, Limits
from ...models import (
    Aggregate,
    AggregateSchedule,
    HistoricalAggregatePoint,
    ReplicationProgress,
    Source,
    WorkingWindowPoint,
)


class AggregateRepository(Protocol):
    def now(self) -> datetime: ...
    def source(self, source_id: UUID) -> Source | None: ...
    def limits(self, limits: Limits, preview: bool) -> None: ...
    def estimate_rows(self, source_id: UUID, start: datetime | None, end: datetime | None, basis: str) -> tuple[int, int, int]: ...
    def calculate(self, source_id: UUID, start: datetime, end: datetime, basis: str, compiled: CompiledRule) -> AggregateStatistics: ...
    def progress(self) -> ReplicationProgress | None: ...
    def coverage_barrier(self, source_id: UUID, end: datetime): ...
    def markerless(self, source_id: UUID, start: datetime, end: datetime) -> bool: ...
    def idempotency_lock(self, key: str) -> None: ...
    def by_key(self, key: str) -> Aggregate | None: ...
    def add(self, aggregate: Aggregate, schedule: AggregateSchedule) -> None: ...
    def get(self, aggregate_id: UUID) -> Aggregate | None: ...
    def schedule(self, schedule_id: UUID, lock: bool = False) -> AggregateSchedule | None: ...
    def refresh(self, aggregate: Aggregate) -> None: ...
    def list(self, limit: int, offset: int) -> tuple[list[Aggregate], int]: ...
    def points(self, aggregate: Aggregate, limit: int, offset: int) -> tuple[list[WorkingWindowPoint | HistoricalAggregatePoint], int]: ...
    def historical(self, aggregate_id: UUID, start: datetime) -> HistoricalAggregatePoint | None: ...
    def add_historical(self, point: HistoricalAggregatePoint) -> None: ...
    def due(self, limit: int) -> list[UUID]: ...
    def record_error(self, aggregate_id: UUID, code: str | None) -> None: ...
