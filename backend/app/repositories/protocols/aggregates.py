"""Aggregate persistence boundary; application decisions remain in services."""

from __future__ import annotations

from datetime import datetime
from typing import Protocol
from uuid import UUID

from ...aggregation.field_catalog import FieldCatalogLimits
from ...aggregation.retention import MembershipCompaction
from ...aggregation.rules import Limits
from ...models import (
    Aggregate,
    AggregateSchedule,
    HistoricalAggregatePoint,
    Source,
    WorkingWindowPoint,
)


class AggregateRepository(Protocol):
    def window_attempt(self, schedule_id, budget): ...
    def history_context(self, aggregate_id, cohort_key, budget): ...
    def add_window_attempt(self, attempt, budget): ...
    def revoke_window_attempt(self, schedule_id, budget=None): ...
    def event_source_rows(self, source_id, budget): ...
    def snapshot_events(self, source_id, start, end, reference_at, budget, *, preview=False, timings=None): ...
    def event_cohorts(self, source_id, start, end, reference_at, budget, memory_limit): ...
    def warmup_payload_preflight(self, schedule_id, starts, before_read): ...
    def event_statistics(self, source_id, start, end, reference_at, compiled, budget): ...
    def received_facts(self, source_id, load_start, load_end, reference_at, budget, coordinates=()): ...
    def closure_at(self, schedule_id, index): ...
    def closure_by_id(self, point_id): ...
    def payload(self, closure): ...
    def snapshot_metadata(self, point_id): ...
    def add_event_point(self, point, closure, membership, metadata, budget): ...
    def scan_page(self, source_id, after, reference, budget): ...
    def save_scan_page(self, aggregate, schedule, page, reference, budget): ...
    def history_candidate(self, aggregate_id, budget): ...
    def history_matches(self, aggregate_id, key, index): ...
    def advance_history(self, aggregate_id, key, index): ...
    def diagnostics(self, aggregate_id): ...
    def aggregate_command(self, actor, action, key, budget): ...
    def save_aggregate_command(self, values, budget): ...
    def protection_detectors(self, aggregate_id, budget, lock=False, maintenance=False): ...
    def cleanup_count(self, aggregate_id, earliest=None): ...
    def cleanup_tail(self, aggregate_id, offset=0): ...
    def canonical_last_index(self, schedule_id): ...
    def warmup_closures(self, schedule_id, first, last): ...
    def prepared_attempt(self, attempt_id, budget): ...
    def add_cleanup_operation(self, values, budget): ...
    def cleanup_operation(self, aggregate_id, operation_id, lock=False): ...
    def cleanup_batch(self, aggregate_id, cutoff, budget): ...
    def compact_point(self, closure, budget): ...
    def maintenance_budget(self, budget): ...
    def add_retention_state(self, aggregate, now): ...
    def maintenance_due(self, limit=100, exclude_ids=()): ...
    def retention_state(self, aggregate_id, budget=None, lock=False): ...
    def last_closed_index(self, schedule_id, budget): ...
    def retention_headers(self, aggregate_id, budget, lock=False): ...
    def retention_dependencies(self, aggregate_id, budget): ...
    def retention_candidate(self, aggregate_id, keep_from, budget, point_id=None, lock=False): ...
    def retention_pending_closure(self, aggregate_id, point_id, budget): ...
    def retention_authorize(self, state, phase, budget): ...
    def clear_payload(self, closure, budget, automatic=False, state=None): ...
    def compact_memberships(self, point_id, budget, automatic=False) -> MembershipCompaction: ...
    def compact_outcomes(self, point_id, budget, automatic=False): ...
    def retention_summary(self, aggregate_id): ...
    def record_aggregate_resume(self, aggregate, schedule, detectors, budget): ...
    def overlap_statistics(self, schedule_id, start, end, base_indices, compiled, budget): ...
    def catalog_limits(self, milliseconds: int, work_mem_mb: int) -> None: ...
    def catalog_preflight(self, source_id: UUID, max_events: int) -> tuple[int, int]: ...
    def catalog_normalizer_size(self, normalizer_id: UUID): ...
    def catalog_normalizer_rule(self, normalizer_id: UUID) -> dict | None: ...
    def catalog_paths(self, source_id: UUID, limits: FieldCatalogLimits, before_read): ...
    def now(self) -> datetime: ...
    def execution_now(self) -> datetime: ...
    def source(self, source_id: UUID) -> Source | None: ...
    def limits(self, limits: Limits, preview: bool, budget=None) -> None: ...
    def read_budget(self, milliseconds: int) -> None: ...
    def estimate_rows(self, source_id: UUID, start: datetime | None, end: datetime | None, basis: str, before_read=None) -> tuple[int, int, int]: ...
    def idempotency_lock(self, key: str) -> None: ...
    def by_key(self, key: str) -> Aggregate | None: ...
    def add(self, aggregate: Aggregate, schedule: AggregateSchedule) -> None: ...
    def get(self, aggregate_id: UUID) -> Aggregate | None: ...
    def schedule(self, schedule_id: UUID, lock: bool = False) -> AggregateSchedule | None: ...
    def refresh(self, aggregate: Aggregate) -> None: ...
    def list(self, limit: int, offset: int, q: str | None = None, state: str | None = None) -> tuple[list[Aggregate], int]: ...
    def points(self, aggregate: Aggregate, limit: int, offset: int) -> tuple[list[WorkingWindowPoint | HistoricalAggregatePoint], int]: ...
    def historical(self, aggregate_id: UUID, start: datetime) -> HistoricalAggregatePoint | None: ...
    def due(self, limit: int, exclude_ids=()) -> list[UUID]: ...
    def record_error(self, aggregate_id: UUID, code: str | None) -> None: ...
