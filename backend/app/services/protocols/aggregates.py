"""HTTP-facing aggregate scenarios."""

from typing import Protocol
from uuid import UUID

from ...models import WorkingWindowPoint
from ...schemas.aggregates import (
    AggregatePreviewRequest,
    CreateAggregateRequest,
    HistoricalRequest,
    ValidateRequest,
)


class AggregateServiceProtocol(Protocol):
    def operators(self) -> list[dict]: ...
    def fields(self, source_id: UUID, query: str | None, limit: int, offset: int): ...
    def validate(self, body: ValidateRequest): ...
    def preview(self, body: AggregatePreviewRequest): ...
    def create(self, body: CreateAggregateRequest, actor: UUID, key: str): ...
    def list(self, limit: int, offset: int, q: str | None = None, state: str | None = None): ...
    def card(self, aggregate_id: UUID): ...
    def points(self, aggregate_id: UUID, limit: int, offset: int): ...
    def copy(self, aggregate_id: UUID): ...
    def lifecycle(self, aggregate_id: UUID, action: str, actor: UUID): ...
    def historical(self, aggregate_id: UUID, body: HistoricalRequest): ...


class AggregateWorkerServiceProtocol(Protocol):
    """Background scenarios without access to a service's internal dependencies."""

    def due(self, limit: int = 1000) -> list[UUID]: ...
    def advance(self, aggregate_id: UUID) -> WorkingWindowPoint: ...
    def record_worker_error(self, aggregate_id: UUID, code: str | None) -> None: ...
