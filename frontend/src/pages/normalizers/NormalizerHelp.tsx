export type HelpTopic = keyof typeof help;

export function ContextHelp({
  topic,
  name,
}: {
  topic: HelpTopic;
  name: string;
}) {
  return (
    <Popover
      title={name}
      content={<span className={styles.helpContent}>{help[topic]}</span>}
      trigger="click"
    >
      <Button
        type="text"
        size="small"
        className={styles.helpButton}
        aria-label={`Справка: ${name}`}
        icon={<InfoCircleOutlined />}
      />
    </Popover>
  );
}

export function helpTopicForLabel(text: string): HelpTopic | null {
  if (text === "Имя" || text === "Описание") return "identity";
  if (text === "Ключ" || text === "Приоритет") return "variant";
  if (text === "Условие" || text === "Значение условия") return "condition";
  if (text.startsWith("Вход:")) return "input";
  if (text === "Шаблон RE2") return "regex";
  if (text === "Шаблон %{field}") return "template";
  if (text.includes("Колонки") || text === "Разделитель") return "columns";
  if (text.includes("JSON-пути") || text === "Имена извлечений и JSON-пути")
    return "json";
  if (text.startsWith("Константы set")) return "set";
  if (text === "Ключ блока") return "blocks";
  if (text === "Обязательное поле") return "required";
  if (
    text === "Источник значения" ||
    text.startsWith("Ссылка") ||
    text.startsWith("Ссылки") ||
    text.startsWith("Константа (JSON")
  )
    return "source";
  if (text.startsWith("Формат даты") || text.startsWith("Явный год"))
    return "date";
  if (text.startsWith("log —")) return "preview";
  if (text === "Полный JSON RuleV1") return "modes";
  return null;
}
